#!/usr/bin/env python3
"""
Generates .pages.yml (the Pages CMS configuration) from content/manifest.yml
and the actual content/*.yml files, so the editor's field list always
matches what's really in the content files. Run this after adding a new
page or a new field to a content YAML file.

Usage: python3 scripts/generate_pages_config.py
"""
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent

LABEL_OVERRIDES = {
    "seo": "SEO", "cta": "CTA", "ctas": "CTAs", "og": "OG", "url": "URL",
    "id": "ID", "sop": "SOP", "sops": "SOPs", "crm": "CRM",
}


def humanize(key):
    key = re.sub(r"(\d+)", r" \1 ", key)
    words = [w for w in key.replace("_", " ").split(" ") if w]
    out = []
    for w in words:
        lw = w.lower()
        out.append(LABEL_OVERRIDES.get(lw, w.capitalize()))
    return " ".join(out)


def is_long(value):
    return len(value) > 60 or "\n" in value


def fields_for(d):
    fields = []
    for key, value in d.items():
        label = humanize(key)
        if isinstance(value, dict):
            fields.append({
                "name": key,
                "label": label,
                "type": "object",
                "fields": fields_for(value),
            })
        else:
            fields.append({
                "name": key,
                "label": label,
                "type": "text" if is_long(str(value)) else "string",
            })
    return fields


def load_yaml(path):
    with open(path, encoding="utf-8") as f:
        return yaml.safe_load(f) or {}


def main():
    manifest = load_yaml(ROOT / "content" / "manifest.yml")

    content = []

    # Shared, sitewide content — edited once, applies everywhere.
    content.append({
        "name": "nav_sitewide",
        "label": "Site-Wide Navigation",
        "type": "file",
        "path": "content/shared/navigation.yml",
        "format": "yaml",
        "fields": fields_for(load_yaml(ROOT / "content" / "shared" / "navigation.yml")),
    })
    content.append({
        "name": "footer_full",
        "label": "Site-Wide Footer (all pages except Homepage)",
        "type": "file",
        "path": "content/shared/footer-full.yml",
        "format": "yaml",
        "fields": fields_for(load_yaml(ROOT / "content" / "shared" / "footer-full.yml")),
    })
    content.append({
        "name": "footer_minimal",
        "label": "Homepage Footer",
        "type": "file",
        "path": "content/shared/footer-minimal.yml",
        "format": "yaml",
        "fields": fields_for(load_yaml(ROOT / "content" / "shared" / "footer-minimal.yml")),
    })

    # One entry per page, in the order pages appear in the manifest.
    for entry in manifest["pages"]:
        content_path = ROOT / entry["content"]
        content.append({
            "name": f"page_{entry['key']}",
            "label": entry.get("label", entry["key"]),
            "type": "file",
            "path": entry["content"],
            "format": "yaml",
            "fields": fields_for(load_yaml(content_path)),
        })

    config = {
        "content": content,
    }

    out_path = ROOT / ".pages.yml"
    header = (
        "# Pages CMS configuration — generated by scripts/generate_pages_config.py\n"
        "# Do not hand-edit the field lists below; edit content/*.yml and the\n"
        "# page/shared files' own keys, then re-run the generator.\n"
        "# Editing fields here only changes labels in the editor, never the\n"
        "# site's HTML/CSS/JS — this file can only ever point at content/*.yml.\n\n"
    )
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(header)
        yaml.safe_dump(config, f, sort_keys=False, allow_unicode=True, width=100)

    print(f"[generate] wrote {out_path} with {len(content)} content entries")


if __name__ == "__main__":
    main()
